/** How a command may get the generated cases when the cache doesn't have them. */
export type Regenerate =
  /**
   * Run the reference to regenerate them, in `sandbox` when given (already prepared), else in the
   * sandbox the config, `noSandbox` and `probe` choose.
   */
  | { noSandbox: boolean; probe?: SandboxProbe; sandbox?: SandboxChoice }
  /** Only from the cache: none when it misses (`report`, which runs no program). */
  | 'cache-only'
  /** Only from the cache of the project this one is a copy of (a mutant check in a copy); none when it misses. */
  | { copyOf: string };

/**
 * The project's corpus: the committed cases (`port-anything/recorded/*.jsonl`), then the generated
 * cases when the config sets `corpus.generator` and `corpus.generator_seed`, leaving out a case
 * already committed. The generated cases come from the cache when it holds them under the current
 * settings, CLI spec and seed fixtures; otherwise, unless `regenerate` says not to, they are
 * regenerated by running the reference (the same cases, being deterministic) and cached.
 */
export async function loadCorpus(projectDir: string, config: Config, regenerate: Regenerate): Promise<CanonicalCase[]> {
  return (await loadProjectCorpus(projectDir, config, regenerate)).cases;
}

/** The project's corpus (see `loadCorpus`), and how its generated cases changed when it had to regenerate them. */
export async function loadProjectCorpus(projectDir: string, config: Config, regenerate: Regenerate): Promise<{ cases: CanonicalCase[]; change?: GeneratedCorpusChange }> {
  const store = new BlobStore(cacheDir(projectDir));
  const committed = await loadCommittedCases(projectDir, store);
  const settings = generatedCorpusSettings(config);
  if (settings === undefined) return { cases: committed };
  let generated: GeneratedCorpusCache | undefined;
  let change: GeneratedCorpusChange | undefined;
  if (regenerate === 'cache-only' || 'copyOf' in regenerate) {
    const inputs = await keyInputs(projectDir, config, settings, 'cache-only');
    if (inputs === undefined) return { cases: committed };
    const from = regenerate === 'cache-only' ? undefined : regenerate.copyOf;
    generated = await readGeneratedCorpusCache(from ?? projectDir, inputs.key, store, from === undefined ? undefined : new BlobStore(cacheDir(from)));
  } else {
    const project = await generateProjectCorpus(projectDir, config, settings, { ...regenerate, force: false });
    generated = project.corpus;
    change = project.change;
  }
  const ids = new Set(committed.map((c) => c.id));
  return { cases: [...committed, ...(generated?.cases ?? []).filter((c) => !ids.has(c.id))], ...(change === undefined ? {} : { change }) };
}

/** How regenerating changed a project's generated cases, against the ones cached before. */
export interface GeneratedCorpusChange {
  /**
   * What differs from the inputs the earlier cases were generated from: only the committed cases
   * (`recorded`: generator v2 mutates them, so adding or editing one changes the generated cases),
   * something else (`other`: the CLI spec, seeds, settings or reference command), or `unknown` when
   * the earlier cache predates the key that tells them apart (generator v2 only).
   */
  cause: 'recorded' | 'other' | 'unknown';
  /** Generated cases per feature (`base` for untagged ones) before and now, for the features whose count changed. */
  features: { feature: string; before: number; now: number }[];
}

/** The change from the cached corpus outline `before` to the generated cases `now`; undefined when they are the same cases. */
export function corpusChange(before: CachedCorpusOutline, now: GeneratedCorpusCache): GeneratedCorpusChange | undefined {
  const ids = new Set(before.cases.map((c) => c.id));
  if (ids.size === now.cases.length && now.cases.every((c) => ids.has(c.id))) return undefined;
  const was = featureCounts(before.cases);
  const is = featureCounts(now.cases);
  const features = [...new Set([...was.keys(), ...is.keys()])]
    .sort()
    .map((feature) => ({ feature, before: was.get(feature) ?? 0, now: is.get(feature) ?? 0 }))
    .filter((f) => f.before !== f.now);
  const cause =
    now.settings.generator === 'v1' ? 'other' : before.keyWithoutCommitted === undefined ? 'unknown' : before.keyWithoutCommitted === now.keyWithoutCommitted ? 'recorded' : 'other';
  return { cause, features };
}

/** The change as `baseline` says it: what changed the generated cases, and their per-feature counts that moved. */
export function corpusChangeLine(change: GeneratedCorpusChange): string {
  const cause = {
    recorded: 'the recorded cases changed the generated ones (generator v2 mutates them)',
    other: 'the generated cases changed since they were last generated (the CLI spec, seeds, settings or reference command changed)',
    unknown: 'the generated cases changed since they were last generated (the CLI spec, seeds, settings, reference command or recorded cases changed)',
  }[change.cause];
  const counts =
    change.features.length === 0
      ? 'the same number per feature'
      : `generated cases per feature, before → now: ${change.features.map((f) => `${f.feature} ${f.before} → ${f.now}`).join(', ')}`;
  return `${cause}; ${counts}`;
}

/** Cases per feature, in feature order; a case without features counts toward `base`, as in scoring. */
export function featureCounts(cases: readonly { features: readonly string[] }[]): Map<string, number> {
  const counts = new Map<string, number>();
  for (const c of cases) for (const f of c.features.length > 0 ? c.features : ['base']) counts.set(f, (counts.get(f) ?? 0) + 1);
  return new Map([...counts].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/**
 * The warning for a weak generated corpus (see `weakCorpusDiagnosis`), or undefined: the spec
 * features without a case and a dominant error answer, whose text is read from `store`.
 */
export async function corpusDiagnosis(stats: CorpusStats, untested: readonly string[], store: BlobStore): Promise<string | undefined> {
  const error = stats.commonestError;
  let text = '';
  if (error !== undefined) {
    const decode = async (ref: string) => new TextDecoder().decode(await store.get(ref));
    text = await decode(error.stderr);
    if (text.trim() === '') text = await decode(error.stdout);
  }
  return weakCorpusDiagnosis({ untested, observed: stats.observed, ...(error === undefined ? {} : { commonestError: { answers: error.answers, text } }) });
}

export interface GenerateProjectOptions {
  noSandbox: boolean;
  probe?: SandboxProbe;
  /** The sandbox to run the reference in, already prepared (in container mode: image pulled, reference built). */
  sandbox?: SandboxChoice;
  /** Regenerate even when the cache holds the corpus (`port-anything generate`). */
  force: boolean;
}

/** A project's generated corpus, and whether it came from the cache. */
export interface ProjectCorpus {
  corpus: GeneratedCorpusCache;
  fromCache: boolean;
  programName: string;
  /** Undefined when the corpus came from the cache. */
  sandbox?: SandboxChoice;
  spec: CliSpec;
  /** When it was regenerated (not forced) over a cache of other cases: how they changed. */
  change?: GeneratedCorpusChange;
}

/**
 * The generated corpus of a project with these settings: from the cache, or generated from the CLI
 * spec and the seed fixtures by running the reference the way `run` does (its sandbox settings and
 * program name), and then cached. Generation is deterministic, so the same settings, spec and
 * reference give the same cases on any checkout.
 */
export async function generateProjectCorpus(projectDir: string, config: Config, settings: GeneratedCorpusSettings, options: GenerateProjectOptions): Promise<ProjectCorpus> {
  const inputs = (await keyInputs(projectDir, config, settings, 'required'))!;
  const store = new BlobStore(cacheDir(projectDir));
  let before: CachedCorpusOutline | undefined;
  if (!options.force) {
    const cached = await readGeneratedCorpusCache(projectDir, inputs.key, store);
    if (cached !== undefined) return { corpus: cached, fromCache: true, programName: inputs.programName, spec: inputs.spec };
    before = await readCachedCorpusOutline(projectDir);
  }
  // In container mode the reference is built in the image first.
  const sandbox =
    options.sandbox ??
    (config.sandbox.mode === 'container'
      ? await prepareContainer(projectDir, config, [], options)
      : chooseSandbox(options.probe ?? (await probeSandbox()), { noSandbox: options.noSandbox }));
  const reference = await resolveReference(config, projectDir);
  const stored = new Set<string>();
  const generated = await withScratchDir(projectDir, 'generate', (workDir) =>
    generateCorpus(inputs.spec, {
      seed: settings.seed,
      generator: settings.generator,
      iKnow: false,
      budget: settings.budget,
      errorPathCap: settings.errorPathCap,
      minCasesPerFeature: settings.minCasesPerFeature,
      seeds: inputs.seeds,
      committed: inputs.committed,
      observe: async (cases, blobs) => {
        for (const c of cases) {
          for (const ref of [c.stdin, ...Object.values(c.fixtures)]) {
            if (ref === null || stored.has(ref)) continue;
            await store.put(blobs.get(ref)!);
            stored.add(ref);
          }
        }
        const run = await runCases({
          reference,
          candidates: [],
          cases,
          store,
          sandbox,
          programName: inputs.programName,
          timeoutMs: config.sandbox.timeout,
          envAllowlist: config.sandbox.env_allowlist,
          env: config.sandbox.env,
          workDir: join(workDir, 'observe'),
        });
        return run.cases.map((c) => c.reference);
      },
    }),
  );
  const corpus: GeneratedCorpusCache = {
    key: inputs.key,
    keyWithoutCommitted: inputs.keyWithoutCommitted,
    settings,
    cases: generated.cases.map((c) => c.case),
    stats: generated.stats,
    skipped: generated.skipped,
  };
  await writeGeneratedCorpusCache(projectDir, corpus);
  const change = before === undefined ? undefined : corpusChange(before, corpus);
  return { corpus, fromCache: false, programName: inputs.programName, sandbox, spec: inputs.spec, ...(change === undefined ? {} : { change }) };
}

/**
 * The cache key of the project's generated corpus and what goes into it. Without a CLI spec, a
 * `ConfigError` when it is `required`, else undefined.
 */
async function keyInputs(
  projectDir: string,
  config: Config,
  settings: GeneratedCorpusSettings,
  spec: 'required' | 'cache-only',
): Promise<{ key: string; keyWithoutCommitted: string; spec: CliSpec; seeds: Uint8Array[]; committed: CommittedParents; programName: string } | undefined> {
  let cliSpec: CliSpec;
  try {
    cliSpec = await readCliSpecFile(projectDir);
  } catch (e) {
    if (spec === 'cache-only') return undefined;
    if (e instanceof ConfigError && e.message.startsWith('No ')) {
      throw new ConfigError(`No ${CLI_SPEC_FILE} to generate the cases from; run port-anything spec infer first.`);
    }
    throw e;
  }
  const seeds = await readSeedFixtures(projectDir);
  const committed = await committedParents(projectDir, settings.generator);
  // The name the reference runs as: the configured one, else the one the spec was read as.
  const programName = config.program_name ?? cliSpec.program;
  const keyInput = {
    settings,
    spec: cliSpec,
    seeds,
    reference: config.reference.cmd,
    programName,
    timeoutMs: config.sandbox.timeout,
    envAllowlist: config.sandbox.env_allowlist,
    env: config.sandbox.env,
  };
  const key = generatedCorpusKey({ ...keyInput, committed: committed.cases });
  return { key, keyWithoutCommitted: generatedCorpusKey(keyInput), spec: cliSpec, seeds, committed, programName };
}

/** The committed cases and their stdin and fixture content, as mutation parents for the generator. */
export type CommittedParents = { cases: CanonicalCase[]; blobs: Map<string, Uint8Array> };

/**
 * The project's committed cases with the content of their inputs, which generator v2 mutates
 * (v1 doesn't, so it gets none and its corpus stays as it was).
 */
export async function committedParents(projectDir: string, generator: GeneratorVersion): Promise<CommittedParents> {
  if (generator === 'v1') return { cases: [], blobs: new Map() };
  const store = new BlobStore(cacheDir(projectDir));
  const cases = await loadCommittedCases(projectDir, store);
  const blobs = new Map<string, Uint8Array>();
  for (const c of cases) {
    for (const ref of [c.stdin, ...Object.values(c.fixtures)]) if (ref !== null && !blobs.has(ref)) blobs.set(ref, await store.get(ref));
  }
  return { cases, blobs };
}

/**
 * Caches a corpus generated elsewhere (by `compare --save`) as the project's generated corpus,
 * under the key of the project's config and CLI spec, with its blobs in the project's store.
 */
export async function cacheGeneratedCorpus(
  projectDir: string,
  config: Config,
  generated: Omit<GeneratedCorpusCache, 'key' | 'settings'> & { blobs: ReadonlyMap<string, Uint8Array> },
): Promise<void> {
  const settings = generatedCorpusSettings(config);
  if (settings === undefined) throw new Error('the config has no generated corpus');
  const { key, keyWithoutCommitted } = (await keyInputs(projectDir, config, settings, 'required'))!;
  const store = new BlobStore(cacheDir(projectDir));
  for (const c of generated.cases) {
    for (const ref of [c.stdin, ...Object.values(c.fixtures)]) if (ref !== null) await store.put(generated.blobs.get(ref)!);
  }
  await writeGeneratedCorpusCache(projectDir, { key, keyWithoutCommitted, settings, cases: generated.cases, stats: generated.stats, skipped: generated.skipped });
}

/** Unknown feature tags a warning lists one by one. */
const LISTED_TAGS = 10;

/**
 * A warning about the feature tags of `port-anything/recorded/*.jsonl` that the CLI spec doesn't
 * define (`base` aside), each with the file and line it first appears on: a typo or a recorder bug
 * (`opt.1` from `-s -16`) would otherwise be scored as a feature of its own without a word.
 * Undefined without a spec, which leaves tags free, or when every tag is known.
 */
export async function unknownFeatureTagsWarning(projectDir: string): Promise<string | undefined> {
  let spec: CliSpec;
  try {
    spec = await readCliSpecFile(projectDir);
  } catch (e) {
    if (e instanceof ConfigError) return undefined;
    throw e;
  }
  const known = new Set([UNTAGGED_FEATURE, ...specFeatures(spec).map((f) => f.name)]);
  const unknown = (await committedFeatureTags(projectDir)).filter((t) => !known.has(t.feature));
  if (unknown.length === 0) return undefined;
  const lines = [`warning: feature tags in ${RECORDED_DIR}/ that ${CLI_SPEC_FILE} does not define (a typo, or a tag of your own, scored as a feature of its own):`];
  for (const t of unknown.slice(0, LISTED_TAGS)) lines.push(`  ${t.feature} · ${t.cases} case${t.cases === 1 ? '' : 's'}, first at ${t.where}`);
  if (unknown.length > LISTED_TAGS) lines.push(`  … and ${unknown.length - LISTED_TAGS} more`);
  return `${lines.join('\n')}\n`;
}
