import { join } from 'node:path';
import {
  BlobStore,
  CLI_SPEC_FILE,
  ConfigError,
  cacheDir,
  chooseSandbox,
  generateCorpus,
  generatedCorpusKey,
  generatedCorpusSettings,
  loadCommittedCases,
  probeSandbox,
  readCliSpecFile,
  readGeneratedCorpusCache,
  readSeedFixtures,
  runCases,
  writeGeneratedCorpusCache,
  type CanonicalCase,
  type CliSpec,
  type Config,
  type GeneratedCorpusCache,
  type GeneratedCorpusSettings,
  type SandboxChoice,
  type SandboxProbe,
} from '@port-anything/core';
import { prepareContainer, resolveCommand, withScratchDir } from './common.js';

/** How a command may get the generated cases when the cache doesn't have them. */
export type Regenerate =
  /**
   * Run the reference to regenerate them, in `sandbox` when given (already prepared), else in the
   * sandbox the config, `noSandbox` and `probe` choose.
   */
  | { noSandbox: boolean; probe?: SandboxProbe; sandbox?: SandboxChoice }
  /** Only from the cache: none when it misses (`report`, which runs no program). */
  | 'cache-only'
  /** Only from the cache of the project this one is a copy of (a mutant check in a copy); none when it misses. */
  | { copyOf: string };

/**
 * The project's corpus: the committed cases (`port-anything/recorded/*.jsonl`), then the generated
 * cases when the config sets `corpus.generator` and `corpus.generator_seed`, leaving out a case
 * already committed. The generated cases come from the cache when it holds them under the current
 * settings, CLI spec and seed fixtures; otherwise, unless `regenerate` says not to, they are
 * regenerated by running the reference (the same cases, being deterministic) and cached.
 */
export async function loadCorpus(projectDir: string, config: Config, regenerate: Regenerate): Promise<CanonicalCase[]> {
  const store = new BlobStore(cacheDir(projectDir));
  const committed = await loadCommittedCases(projectDir, store);
  const settings = generatedCorpusSettings(config);
  if (settings === undefined) return committed;
  let generated: GeneratedCorpusCache | undefined;
  if (regenerate === 'cache-only' || 'copyOf' in regenerate) {
    const inputs = await keyInputs(projectDir, config, settings, 'cache-only');
    if (inputs === undefined) return committed;
    const from = regenerate === 'cache-only' ? undefined : regenerate.copyOf;
    generated = await readGeneratedCorpusCache(from ?? projectDir, inputs.key, store, from === undefined ? undefined : new BlobStore(cacheDir(from)));
  } else {
    generated = (await generateProjectCorpus(projectDir, config, settings, { ...regenerate, force: false })).corpus;
  }
  const ids = new Set(committed.map((c) => c.id));
  return [...committed, ...(generated?.cases ?? []).filter((c) => !ids.has(c.id))];
}

export interface GenerateProjectOptions {
  noSandbox: boolean;
  probe?: SandboxProbe;
  /** The sandbox to run the reference in, already prepared (in container mode: image pulled, reference built). */
  sandbox?: SandboxChoice;
  /** Regenerate even when the cache holds the corpus (`port-anything generate`). */
  force: boolean;
}

/** A project's generated corpus, and whether it came from the cache. */
export interface ProjectCorpus {
  corpus: GeneratedCorpusCache;
  fromCache: boolean;
  programName: string;
  /** Undefined when the corpus came from the cache. */
  sandbox?: SandboxChoice;
  spec: CliSpec;
}

/**
 * The generated corpus of a project with these settings: from the cache, or generated from the CLI
 * spec and the seed fixtures by running the reference the way `run` does (its sandbox settings and
 * program name), and then cached. Generation is deterministic, so the same settings, spec and
 * reference give the same cases on any checkout.
 */
export async function generateProjectCorpus(projectDir: string, config: Config, settings: GeneratedCorpusSettings, options: GenerateProjectOptions): Promise<ProjectCorpus> {
  const inputs = (await keyInputs(projectDir, config, settings, 'required'))!;
  const store = new BlobStore(cacheDir(projectDir));
  if (!options.force) {
    const cached = await readGeneratedCorpusCache(projectDir, inputs.key, store);
    if (cached !== undefined) return { corpus: cached, fromCache: true, programName: inputs.programName, spec: inputs.spec };
  }
  // In container mode the reference is built in the image first.
  const sandbox =
    options.sandbox ??
    (config.sandbox.mode === 'container'
      ? await prepareContainer(projectDir, config, [], options)
      : chooseSandbox(options.probe ?? (await probeSandbox()), { noSandbox: options.noSandbox }));
  const reference = await resolveCommand(config.reference.cmd, projectDir);
  const stored = new Set<string>();
  const generated = await withScratchDir(projectDir, 'generate', (workDir) =>
    generateCorpus(inputs.spec, {
      seed: settings.seed,
      generator: settings.generator,
      iKnow: false,
      budget: settings.budget,
      errorPathCap: settings.errorPathCap,
      minCasesPerFeature: settings.minCasesPerFeature,
      seeds: inputs.seeds,
      observe: async (cases, blobs) => {
        for (const c of cases) {
          for (const ref of [c.stdin, ...Object.values(c.fixtures)]) {
            if (ref === null || stored.has(ref)) continue;
            await store.put(blobs.get(ref)!);
            stored.add(ref);
          }
        }
        const run = await runCases({
          reference,
          candidates: [],
          cases,
          store,
          sandbox,
          programName: inputs.programName,
          timeoutMs: config.sandbox.timeout,
          envAllowlist: config.sandbox.env_allowlist,
          env: config.sandbox.env,
          workDir: join(workDir, 'observe'),
        });
        return run.cases.map((c) => c.reference);
      },
    }),
  );
  const corpus: GeneratedCorpusCache = { key: inputs.key, settings, cases: generated.cases.map((c) => c.case), stats: generated.stats, skipped: generated.skipped };
  await writeGeneratedCorpusCache(projectDir, corpus);
  return { corpus, fromCache: false, programName: inputs.programName, sandbox, spec: inputs.spec };
}

/**
 * The cache key of the project's generated corpus and what goes into it. Without a CLI spec, a
 * `ConfigError` when it is `required`, else undefined.
 */
async function keyInputs(
  projectDir: string,
  config: Config,
  settings: GeneratedCorpusSettings,
  spec: 'required' | 'cache-only',
): Promise<{ key: string; spec: CliSpec; seeds: Uint8Array[]; programName: string } | undefined> {
  let cliSpec: CliSpec;
  try {
    cliSpec = await readCliSpecFile(projectDir);
  } catch (e) {
    if (spec === 'cache-only') return undefined;
    if (e instanceof ConfigError && e.message.startsWith('No ')) {
      throw new ConfigError(`No ${CLI_SPEC_FILE} to generate the cases from; run port-anything spec infer first.`);
    }
    throw e;
  }
  const seeds = await readSeedFixtures(projectDir);
  // The name the reference runs as: the configured one, else the one the spec was read as.
  const programName = config.program_name ?? cliSpec.program;
  const key = generatedCorpusKey({
    settings,
    spec: cliSpec,
    seeds,
    reference: config.reference.cmd,
    programName,
    timeoutMs: config.sandbox.timeout,
    envAllowlist: config.sandbox.env_allowlist,
    env: config.sandbox.env,
  });
  return { key, spec: cliSpec, seeds, programName };
}

/**
 * Caches a corpus generated elsewhere (by `compare --save`) as the project's generated corpus,
 * under the key of the project's config and CLI spec, with its blobs in the project's store.
 */
export async function cacheGeneratedCorpus(
  projectDir: string,
  config: Config,
  generated: Omit<GeneratedCorpusCache, 'key' | 'settings'> & { blobs: ReadonlyMap<string, Uint8Array> },
): Promise<void> {
  const settings = generatedCorpusSettings(config);
  if (settings === undefined) throw new Error('the config has no generated corpus');
  const { key } = (await keyInputs(projectDir, config, settings, 'required'))!;
  const store = new BlobStore(cacheDir(projectDir));
  for (const c of generated.cases) {
    for (const ref of [c.stdin, ...Object.values(c.fixtures)]) if (ref !== null) await store.put(generated.blobs.get(ref)!);
  }
  await writeGeneratedCorpusCache(projectDir, { key, settings, cases: generated.cases, stats: generated.stats, skipped: generated.skipped });
}
